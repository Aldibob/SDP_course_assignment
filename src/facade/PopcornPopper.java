package facade;

public class PopcornPopper {

    public void On() {
        System.out.println("Popcorn-Popper on");
    }

    public void Pop() {
        System.out.println("Popcorn-Popper popping popcorn!");
    }

    public void Off() {
        System.out.println("Popcorn-Popper off");
    }
}
